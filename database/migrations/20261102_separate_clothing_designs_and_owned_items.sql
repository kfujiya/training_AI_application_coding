BEGIN;

DO $migration$
DECLARE
	design_rows_before BIGINT;
	doll_links_before BIGINT;
	owned_rows_after BIGINT;
	doll_links_after BIGINT;
	foreign_key RECORD;
BEGIN
	IF to_regclass('"Clothing_Designs"') IS NOT NULL THEN
		RAISE NOTICE 'Clothing design migration already applied; skipping.';
		RETURN;
	END IF;

	IF to_regclass('"Clothing_Items"') IS NULL OR to_regclass('"Clothing_Item_Dolls"') IS NULL THEN
		RAISE EXCEPTION 'Expected Clothing_Items and Clothing_Item_Dolls tables were not found.';
	END IF;

	SELECT count(*) INTO design_rows_before FROM "Clothing_Items";
	SELECT count(*) INTO doll_links_before FROM "Clothing_Item_Dolls";

	ALTER TABLE "Clothing_Items" RENAME TO "Clothing_Designs";
	ALTER TABLE "Clothing_Designs" RENAME COLUMN "Clothing_Item_ID" TO "Clothing_Design_ID";
	ALTER TABLE "Clothing_Designs" RENAME COLUMN "Item_Name" TO "Design_Name";
	ALTER TABLE "Clothing_Designs" ADD COLUMN "Description" TEXT;

	CREATE TABLE "Clothing_Items" (
		"Clothing_Item_ID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		"Clothing_Design_ID" BIGINT NOT NULL
			REFERENCES "Clothing_Designs" ("Clothing_Design_ID") ON DELETE RESTRICT,
		"Color_Name" VARCHAR(100),
		"Color_Hex" VARCHAR(7),
		"Size" VARCHAR(50),
		"Notes" TEXT,
		"Created_At" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
		"Updated_At" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
		CONSTRAINT "CK_Clothing_Items_Color_Hex"
			CHECK ("Color_Hex" IS NULL OR "Color_Hex" ~ '^#[0-9A-Fa-f]{6}$')
	);

	INSERT INTO "Clothing_Items" (
		"Clothing_Item_ID", "Clothing_Design_ID", "Size", "Notes", "Created_At", "Updated_At"
	)
	SELECT d."Clothing_Design_ID", d."Clothing_Design_ID", d."Size", d."Notes",
	       d."Created_At", d."Updated_At"
	FROM "Clothing_Designs" d
	ORDER BY d."Clothing_Design_ID";

	PERFORM setval(
		pg_get_serial_sequence('"Clothing_Items"', 'Clothing_Item_ID'),
		COALESCE((SELECT max("Clothing_Item_ID") FROM "Clothing_Items"), 1),
		EXISTS (SELECT 1 FROM "Clothing_Items")
	);

	FOR foreign_key IN
		SELECT conname
		FROM pg_constraint
		WHERE conrelid = to_regclass('"Clothing_Item_Dolls"')
		  AND confrelid = to_regclass('"Clothing_Designs"')
		  AND contype = 'f'
	LOOP
		EXECUTE format('ALTER TABLE "Clothing_Item_Dolls" DROP CONSTRAINT %I', foreign_key.conname);
	END LOOP;

	ALTER TABLE "Clothing_Item_Dolls"
		ADD CONSTRAINT "FK_Clothing_Item_Dolls_Clothing_Items"
		FOREIGN KEY ("Clothing_Item_ID")
		REFERENCES "Clothing_Items" ("Clothing_Item_ID")
		ON DELETE CASCADE;

	CREATE INDEX "IDX_Clothing_Items_Design_ID"
		ON "Clothing_Items" ("Clothing_Design_ID");
	CREATE INDEX "IDX_Clothing_Item_Dolls_Doll_ID"
		ON "Clothing_Item_Dolls" ("Doll_ID", "Clothing_Item_ID");
	CREATE INDEX "IDX_Clothing_Designs_Brand_Set"
		ON "Clothing_Designs" ("Brand_ID", "Set_Name");

	ALTER TABLE "Clothing_Designs" DROP COLUMN "Size";
	ALTER TABLE "Clothing_Designs" DROP COLUMN "Notes";

	SELECT count(*) INTO owned_rows_after FROM "Clothing_Items";
	SELECT count(*) INTO doll_links_after FROM "Clothing_Item_Dolls";
	IF owned_rows_after <> design_rows_before THEN
		RAISE EXCEPTION 'Owned item row count mismatch: expected %, found %.',
			design_rows_before, owned_rows_after;
	END IF;
	IF doll_links_after <> doll_links_before THEN
		RAISE EXCEPTION 'Doll link row count mismatch: expected %, found %.',
			doll_links_before, doll_links_after;
	END IF;

	RAISE NOTICE 'Migrated % clothing designs, % owned items, and % doll links.',
		design_rows_before, owned_rows_after, doll_links_after;
END
$migration$;

COMMIT;

SELECT 'Clothing_Designs' AS table_name, count(*) AS row_count FROM "Clothing_Designs"
UNION ALL
SELECT 'Clothing_Items', count(*) FROM "Clothing_Items"
UNION ALL
SELECT 'Clothing_Item_Dolls', count(*) FROM "Clothing_Item_Dolls";
